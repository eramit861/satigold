/** contact.php only accepts form POSTs, so crawlers have nothing to index there. */
const buildRobots = () => `User-agent: *\nAllow: /\nDisallow: /contact.php\n\nSitemap: ${absoluteUrl('/sitemap.xml')}\n`

/** Product photos shown on the page, listed for Google Images. */
const SITEMAP_IMAGES = [
    ...new Set([SITE.ogImage, '/images/hero-jar.webp', '/images/himalayas-to-home.webp', ...GALLERY.map((image) => image.src)]),
]

function buildSitemap() {
    const lastModified = new Date().toISOString().slice(0, 10)
    const images = SITEMAP_IMAGES.map(
        (src) => `    <image:image>\n      <image:loc>${escapeHtml(absoluteUrl(src))}</image:loc>\n    </image:image>`,
    ).join('\n')

    return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${absoluteUrl('/')}</loc>
    <lastmod>${lastModified}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
${images}
  </url>
</urlset>
`
}

/** Apache/LiteSpeed rules for Hostinger. The www rule is host-agnostic so it works on any domain. */
function buildHtaccess() {
    const prefersWww = new URL(SITE.url).hostname.startsWith('www.')
    const canonicalHostRule = prefersWww
        ? `  # Canonical host: add www\n  RewriteCond %{HTTP_HOST} !^www\\. [NC]\n  RewriteRule ^ https://www.%{HTTP_HOST}%{REQUEST_URI} [L,R=301]`
        : `  # Canonical host: strip www\n  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]\n  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]`

    return `# ${SITE.productName} - Hostinger static deploy (generated by vite.config.js)
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Force HTTPS
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

${canonicalHostRule}

  # /index.html -> /
  RewriteCond %{THE_REQUEST} \\s/index\\.html[\\s?] [NC]
  RewriteRule ^index\\.html$ / [L,R=301]
</IfModule>

# SMTP credentials used by contact.php
<Files "contact-config.php">
  Require all denied
</Files>

AddType application/manifest+json .webmanifest
AddType image/webp .webp

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml application/javascript application/json application/xml application/manifest+json image/svg+xml
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"

  # Hashed build files never change
  <FilesMatch "-[A-Za-z0-9_-]{8}\\.(js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>

  <FilesMatch "\\.(webp|jpg|jpeg|png|ico|svg)$">
    Header set Cache-Control "public, max-age=2592000"
  </FilesMatch>

  <FilesMatch "\\.(html|xml|txt|webmanifest)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`
}

function buildManifest() {
    return JSON.stringify(
        {
            name: SITE.productName,
            short_name: SITE.name,
            description: SITE.description,
            start_url: '/',
            display: 'standalone',
            background_color: '#FBF5E6',
            theme_color: SITE.themeColor,
            icons: [
                { src: '/android-chrome-192x192.png', sizes: '192x192', type: 'image/png' },
                { src: '/android-chrome-512x512.png', sizes: '512x512', type: 'image/png' },
            ],
        },
        null,
        4,
    )
}

/** Fills __TOKENS__ in index.html from src/config/site.js and emits robots.txt, sitemap.xml, site.webmanifest and .htaccess. */
function siteSeoPlugin() {
    let isSsrBuild = false

    const tokens = {
        SITE_LANGUAGE: SITE.language,
        SITE_TITLE: escapeHtml(SITE.title),
        SITE_DESCRIPTION: escapeHtml(SITE.description),
        SITE_KEYWORDS: escapeHtml(SITE.keywords.join(', ')),
        SITE_NAME: escapeHtml(SITE.name),
        SITE_PRODUCT_NAME: escapeHtml(SITE.productName),
        SITE_LOCALE: SITE.locale,
        SITE_URL: absoluteUrl('/'),
        THEME_COLOR: SITE.themeColor,
        GEO_REGION: SITE.address.regionCode,
        GEO_PLACENAME: escapeHtml(`${SITE.address.district}, ${SITE.address.region}`),
        OG_IMAGE: absoluteUrl(SITE.ogImage),
        OG_IMAGE_ALT: escapeHtml(SITE.ogImageAlt),
        STRUCTURED_DATA: JSON.stringify(buildStructuredData()).replace(/</g, '\\u003c'),
    }

    return {
        name: 'sati-gold-seo',
        configResolved(config) {
            isSsrBuild = Boolean(config.build.ssr)
        },
        transformIndexHtml: {
            order: 'pre',
            handler: (html) => html.replace(/__([A-Z]+(?:_[A-Z]+)*)__/g, (match, key) => tokens[key] ?? match),
        },
        configureServer(server) {
            const devFiles = {
                '/site.webmanifest': ['application/manifest+json', buildManifest],
                '/robots.txt': ['text/plain', buildRobots],
                '/sitemap.xml': ['application/xml', buildSitemap],
            }
            server.middlewares.use((req, res, next) => {
                const file = devFiles[req.url]
                if (!file) {
                    return next()
                }
                res.setHeader('Content-Type', file[0])
                res.end(file[1]())
            })
        },
        generateBundle() {
            if (isSsrBuild) {
                return
            }
            this.emitFile({ type: 'asset', fileName: 'robots.txt', source: buildRobots() })
            this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: buildSitemap() })
            this.emitFile({ type: 'asset', fileName: 'site.webmanifest', source: buildManifest() })
            this.emitFile({ type: 'asset', fileName: '.htaccess', source: buildHtaccess() })
        },
    }
}

/** Fonts used above the fold: the hero heading (700 and its italic gold line) and the lead paragraph (400). */
const PRELOAD_FONTS = [
    'libre-baskerville-latin-700-normal',
    'libre-baskerville-latin-400-italic',
    'libre-baskerville-latin-400-normal',
]

/**
 * Inlines the stylesheet (about 7 KB gzipped) so it no longer blocks the first paint,
 * and preloads the hero fonts so they arrive alongside the HTML.
 */
function criticalAssetsPlugin() {
    return {
        name: 'sati-gold-critical-assets',
        apply: 'build',
        transformIndexHtml: {
            order: 'post',
            handler(html, ctx) {
                if (!ctx.bundle) {
                    return html
                }
                const assets = Object.values(ctx.bundle).filter((file) => file.type === 'asset')

                let output = html
                for (const css of assets.filter((file) => file.fileName.endsWith('.css'))) {
                    const linkTag = new RegExp(`<link rel="stylesheet"[^>]*href="/${css.fileName}"[^>]*>`)
                    output = output.replace(linkTag, () => `<style>${css.source}</style>`)
                }

                const tags = PRELOAD_FONTS.map((name) =>
                    assets.find((file) => file.fileName.endsWith('.woff2') && path.basename(file.fileName).startsWith(`${name}-`)),
                )
                    .filter(Boolean)
                    .map((font) => ({
                        tag: 'link',
                        attrs: { rel: 'preload', href: `/${font.fileName}`, as: 'font', type: 'font/woff2', crossorigin: '' },
                        injectTo: 'head',
                    }))

                return { html: output, tags }
            },
        },
    }
}

export default defineConfig({
    plugins: [preact(), siteSeoPlugin(), criticalAssetsPlugin()],
    build: {
        cssCodeSplit: false,
        assetsInlineLimit: 0,
    },
})
